create or replace function public.resolve_live_view_city_v1(
  p_workspace_id uuid,
  p_city text,
  p_country text default null
)
returns table (
  city text, region text, country text, country_code text,
  latitude double precision, longitude double precision,
  geo_source text, geo_confidence text
)
language sql stable security definer set search_path = ''
as $function$
  with input as (
    select lower(regexp_replace(btrim(coalesce(p_city,'')), '[^[:alnum:]]+', '', 'g')) n,
           upper(btrim(coalesce(p_country,''))) c
  ), mapped as (
    select catalog.*, alias.workspace_id
    from public.live_view_city_aliases alias
    join public.live_view_city_catalog catalog on catalog.id = alias.city_id
    cross join input
    where alias.normalized_alias = input.n
      and (alias.workspace_id = p_workspace_id or alias.workspace_id is null)
      and (input.c = '' or input.c in (catalog.country_code, upper(catalog.country_name)))
    order by (alias.workspace_id is not null) desc
    limit 1
  )
  select mapped.canonical_name, mapped.region, mapped.country_name, mapped.country_code,
         mapped.latitude, mapped.longitude,
         case when mapped.workspace_id is null then 'city' else 'provider_city' end,
         'medium'
  from mapped
$function$;
revoke all on function public.resolve_live_view_city_v1(uuid,text,text) from public;
grant execute on function public.resolve_live_view_city_v1(uuid,text,text) to service_role;

create or replace function public.project_live_view_order_v1()
returns trigger language plpgsql security definer set search_path = ''
as $function$
declare resolved record;
begin
  select * into resolved
  from public.resolve_live_view_city_v1(new.workspace_id, coalesce(new.city,new.raw_city), new.country)
  limit 1;

  insert into public.live_view_events (
    order_id, workspace_id, occurred_at, status, total, currency, source,
    product_name, campaign, city, region, country, country_code,
    latitude, longitude, geo_source, geo_confidence, updated_at
  ) values (
    new."Order ID", new.workspace_id, coalesce(new.order_date,new.created_at),
    coalesce(new.status,'unknown'), coalesce(new.total,0), new.currency,
    coalesce(new.source_platform,new.source,new.utm_source), new.product_name,
    new.utm_campaign, coalesce(resolved.city,new.city,new.raw_city),
    coalesce(resolved.region,new.region), coalesce(resolved.country,new.country),
    resolved.country_code, resolved.latitude, resolved.longitude,
    coalesce(resolved.geo_source,case when nullif(btrim(new.country),'') is not null then 'country' else 'unknown' end),
    coalesce(resolved.geo_confidence,'low'), now()
  )
  on conflict (order_id) do update set
    workspace_id=excluded.workspace_id, occurred_at=excluded.occurred_at,
    status=excluded.status, total=excluded.total, currency=excluded.currency,
    source=excluded.source, product_name=excluded.product_name,
    campaign=excluded.campaign,
    city=case when public.live_view_events.geo_source='ip' then public.live_view_events.city else excluded.city end,
    region=case when public.live_view_events.geo_source='ip' then public.live_view_events.region else excluded.region end,
    country=case when public.live_view_events.geo_source='ip' then public.live_view_events.country else excluded.country end,
    country_code=case when public.live_view_events.geo_source='ip' then public.live_view_events.country_code else excluded.country_code end,
    latitude=case when public.live_view_events.geo_source='ip' then public.live_view_events.latitude else excluded.latitude end,
    longitude=case when public.live_view_events.geo_source='ip' then public.live_view_events.longitude else excluded.longitude end,
    geo_source=case when public.live_view_events.geo_source='ip' then 'ip' else excluded.geo_source end,
    geo_confidence=case when public.live_view_events.geo_source='ip' then public.live_view_events.geo_confidence else excluded.geo_confidence end,
    updated_at=now();
  return new;
end
$function$;

drop trigger if exists orders_live_view_projection on public.orders;
create trigger orders_live_view_projection
after insert or update of status,total,currency,source,source_platform,product_name,utm_campaign,city,raw_city,region,country,order_date
on public.orders for each row execute function public.project_live_view_order_v1();

insert into public.live_view_events (
  order_id, workspace_id, occurred_at, status, total, currency, source,
  product_name, campaign, city, region, country, country_code,
  latitude, longitude, geo_source, geo_confidence
)
select o."Order ID",o.workspace_id,coalesce(o.order_date,o.created_at),o.status,
       coalesce(o.total,0),o.currency,coalesce(o.source_platform,o.source,o.utm_source),
       o.product_name,o.utm_campaign,coalesce(r.city,o.city,o.raw_city),
       coalesce(r.region,o.region),coalesce(r.country,o.country),r.country_code,
       r.latitude,r.longitude,
       coalesce(r.geo_source,case when nullif(btrim(o.country),'') is not null then 'country' else 'unknown' end),
       coalesce(r.geo_confidence,'low')
from public.orders o
left join lateral public.resolve_live_view_city_v1(o.workspace_id,coalesce(o.city,o.raw_city),o.country) r on true
on conflict (order_id) do nothing;

create or replace function public.get_live_view_snapshot_v1(
  p_workspace_id uuid,
  p_window text default '15m',
  p_filters jsonb default '{}'::jsonb,
  p_admin_global boolean default false
)
returns jsonb language plpgsql stable security definer set search_path = ''
as $function$
declare since_at timestamptz; result jsonb;
begin
  if (select auth.uid()) is null then raise exception 'Authentication required'; end if;
  if p_admin_global then
    if not public.has_platform_permission('orders.read_all') then raise exception 'Access denied'; end if;
  elsif p_workspace_id is null or not public.is_active_workspace_member(p_workspace_id) then
    raise exception 'Access denied';
  end if;

  since_at := case lower(coalesce(p_window,'15m'))
    when 'live' then now() - interval '2 minutes'
    when '1m' then now() - interval '1 minute'
    when '5m' then now() - interval '5 minutes'
    when '15m' then now() - interval '15 minutes'
    when '1h' then now() - interval '1 hour'
    when 'today' then date_trunc('day',now())
    else now() - interval '15 minutes' end;

  with filtered as (
    select e.*, w.name workspace_name
    from public.live_view_events e
    join public.workspaces w on w.id=e.workspace_id
    where e.occurred_at >= since_at
      and (p_admin_global or e.workspace_id=p_workspace_id)
      and (nullif(p_filters->>'status','') is null or lower(e.status)=lower(p_filters->>'status'))
      and (nullif(p_filters->>'source','') is null or lower(coalesce(e.source,''))=lower(p_filters->>'source'))
      and (nullif(p_filters->>'product','') is null or lower(coalesce(e.product_name,''))=lower(p_filters->>'product'))
      and (nullif(p_filters->>'city','') is null or lower(coalesce(e.city,''))=lower(p_filters->>'city'))
      and (nullif(p_filters->>'campaign','') is null or lower(coalesce(e.campaign,''))=lower(p_filters->>'campaign'))
      and (nullif(p_filters->>'country','') is null or lower(coalesce(e.country,''))=lower(p_filters->>'country'))
      and (nullif(p_filters->>'workspace_id','') is null or e.workspace_id::text=p_filters->>'workspace_id')
  ), recent as (
    select * from filtered order by occurred_at desc limit 200
  ), option_source as (
    select jsonb_build_object(
      'statuses',coalesce((select jsonb_agg(x) from (select distinct status x from filtered where status is not null order by 1) q),'[]'::jsonb),
      'sources',coalesce((select jsonb_agg(x) from (select distinct source x from filtered where source is not null order by 1) q),'[]'::jsonb),
      'products',coalesce((select jsonb_agg(x) from (select distinct product_name x from filtered where product_name is not null order by 1) q),'[]'::jsonb),
      'cities',coalesce((select jsonb_agg(x) from (select distinct city x from filtered where city is not null order by 1) q),'[]'::jsonb),
      'campaigns',coalesce((select jsonb_agg(x) from (select distinct campaign x from filtered where campaign is not null order by 1) q),'[]'::jsonb),
      'countries',coalesce((select jsonb_agg(x) from (select distinct country x from filtered where country is not null order by 1) q),'[]'::jsonb),
      'workspaces',coalesce((select jsonb_agg(jsonb_build_object('id',workspace_id,'name',workspace_name)) from (select distinct workspace_id,workspace_name from filtered order by workspace_name) q),'[]'::jsonb)
    ) options
  )
  select jsonb_build_object(
    'generated_at',now(),
    'orders',coalesce((select count(*) from filtered),0),
    'revenue_by_currency',coalesce((select jsonb_object_agg(currency,total) from (select coalesce(currency,'—') currency,sum(total) total from filtered group by 1) q),'{}'::jsonb),
    'events',coalesce((select jsonb_agg(jsonb_build_object(
      'order_id',order_id,'workspace_id',workspace_id,'workspace_name',workspace_name,
      'occurred_at',occurred_at,'status',status,'total',total,'currency',currency,
      'source',source,'product_name',product_name,'campaign',campaign,'city',city,
      'region',region,'country',country,'country_code',country_code,
      'latitude',latitude,'longitude',longitude,'geo_source',geo_source,'geo_confidence',geo_confidence
    ) order by occurred_at desc) from recent),'[]'::jsonb),
    'top_cities',coalesce((select jsonb_agg(to_jsonb(q)) from (select coalesce(city,'Unknown') label,count(*) orders,sum(total) revenue from filtered group by 1 order by orders desc limit 8) q),'[]'::jsonb),
    'top_products',coalesce((select jsonb_agg(to_jsonb(q)) from (select coalesce(product_name,'Unknown') label,count(*) orders,sum(total) revenue from filtered group by 1 order by orders desc limit 8) q),'[]'::jsonb),
    'top_sources',coalesce((select jsonb_agg(to_jsonb(q)) from (select coalesce(source,'Unknown') label,count(*) orders,sum(total) revenue from filtered group by 1 order by orders desc limit 8) q),'[]'::jsonb),
    'top_campaigns',coalesce((select jsonb_agg(to_jsonb(q)) from (select coalesce(campaign,'Unattributed') label,count(*) orders,sum(total) revenue from filtered group by 1 order by orders desc limit 8) q),'[]'::jsonb),
    'top_workspaces',case when p_admin_global then coalesce((select jsonb_agg(to_jsonb(q)) from (select workspace_id,workspace_name label,count(*) orders,sum(total) revenue from filtered group by 1,2 order by orders desc limit 8) q),'[]'::jsonb) else '[]'::jsonb end,
    'options',(select options from option_source)
  ) into result;
  return result;
end
$function$;

revoke all on function public.get_live_view_snapshot_v1(uuid,text,jsonb,boolean) from public;
grant execute on function public.get_live_view_snapshot_v1(uuid,text,jsonb,boolean) to authenticated;

