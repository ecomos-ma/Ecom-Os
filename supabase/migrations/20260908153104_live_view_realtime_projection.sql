-- Privacy-safe realtime projection for the Live View.
-- Raw customer IP addresses remain exclusively on public.orders.

create table if not exists public.live_view_city_catalog (
  id bigint generated by default as identity primary key,
  canonical_name text not null,
  country_code text not null check (char_length(country_code) = 2),
  country_name text not null,
  region text,
  latitude double precision not null check (latitude between -90 and 90),
  longitude double precision not null check (longitude between -180 and 180),
  source text not null default 'geonames',
  created_at timestamptz not null default now(),
  unique (canonical_name, country_code)
);

create table if not exists public.live_view_city_aliases (
  id bigint generated by default as identity primary key,
  city_id bigint not null references public.live_view_city_catalog(id) on delete cascade,
  workspace_id uuid references public.workspaces(id) on delete cascade,
  alias text not null,
  normalized_alias text generated always as (
    lower(regexp_replace(btrim(alias), '[^[:alnum:]]+', '', 'g'))
  ) stored,
  created_at timestamptz not null default now()
);

create unique index if not exists live_view_city_aliases_global_uq
  on public.live_view_city_aliases (normalized_alias)
  where workspace_id is null;
create unique index if not exists live_view_city_aliases_workspace_uq
  on public.live_view_city_aliases (workspace_id, normalized_alias)
  where workspace_id is not null;
create index if not exists live_view_city_aliases_city_idx
  on public.live_view_city_aliases (city_id);

create table if not exists public.live_view_geo_cache (
  ip_hash text primary key check (char_length(ip_hash) = 64),
  city text,
  region text,
  country text,
  country_code text,
  latitude double precision check (latitude between -90 and 90),
  longitude double precision check (longitude between -180 and 180),
  provider text not null,
  confidence text not null check (confidence in ('high', 'medium', 'low')),
  resolved_at timestamptz not null default now(),
  expires_at timestamptz not null
);
create index if not exists live_view_geo_cache_expiry_idx
  on public.live_view_geo_cache (expires_at);

create table if not exists public.live_view_events (
  order_id uuid primary key references public.orders("Order ID") on delete cascade,
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  occurred_at timestamptz not null,
  status text not null,
  total numeric not null default 0,
  currency text,
  source text,
  product_name text,
  campaign text,
  city text,
  region text,
  country text,
  country_code text,
  latitude double precision check (latitude between -90 and 90),
  longitude double precision check (longitude between -180 and 180),
  geo_source text not null default 'unknown'
    check (geo_source in ('ip', 'city', 'provider_city', 'region', 'country', 'unknown')),
  geo_confidence text not null default 'low'
    check (geo_confidence in ('high', 'medium', 'low')),
  updated_at timestamptz not null default now()
);

create index if not exists live_view_events_workspace_time_idx
  on public.live_view_events (workspace_id, occurred_at desc);
create index if not exists live_view_events_time_idx
  on public.live_view_events (occurred_at desc);
create index if not exists live_view_events_workspace_city_idx
  on public.live_view_events (workspace_id, city, occurred_at desc);

alter table public.live_view_city_catalog enable row level security;
alter table public.live_view_city_aliases enable row level security;
alter table public.live_view_geo_cache enable row level security;
alter table public.live_view_events enable row level security;

drop policy if exists live_view_catalog_read on public.live_view_city_catalog;
create policy live_view_catalog_read on public.live_view_city_catalog
  for select to authenticated using (true);

drop policy if exists live_view_aliases_read on public.live_view_city_aliases;
create policy live_view_aliases_read on public.live_view_city_aliases
  for select to authenticated using (
    workspace_id is null
    or (select public.is_active_workspace_member(workspace_id))
    or (select public.has_platform_permission('orders.read_all'))
  );

drop policy if exists live_view_events_read on public.live_view_events;
create policy live_view_events_read on public.live_view_events
  for select to authenticated using (
    (select public.is_active_workspace_member(workspace_id))
    or (select public.has_platform_permission('orders.read_all'))
  );

revoke all on table public.live_view_geo_cache from anon, authenticated;
revoke all on table public.live_view_city_catalog from anon;
revoke all on table public.live_view_city_aliases from anon;
revoke all on table public.live_view_events from anon;
grant select on public.live_view_city_catalog, public.live_view_city_aliases, public.live_view_events to authenticated;

